"""Ad-hoc: list every item flag in the normalized files, with counts and first/last month.

Run by hand::

    uv run python adhoc/flag_inventory.py            # print the Markdown table
    uv run python adhoc/flag_inventory.py --write    # replace the generated block in
                                                     # documentation/flag_and_code_definitions.md

The table is the corpus-side half of ``documentation/flag_and_code_definitions.md``: the definitions are the
publisher's, the inventory shows which flags really occur and whether the normalizer knows them.
"""

import csv
from collections import Counter
from pathlib import Path
from typing import Annotated

import typer

from cof.common.settings import PROJECT_ROOT, Settings
from cof.normalize.items import KNOWN_FLAGS

START = "<!-- flag-inventory:start (generated by adhoc/flag_inventory.py; do not edit) -->"
END = "<!-- flag-inventory:end -->"
DOC = PROJECT_ROOT / "documentation" / "flag_and_code_definitions.md"


def inventory(normalized_dir: Path) -> str:
    """Build the Markdown table of flags found in the normalized item rows.

    Args:
        normalized_dir: Directory with the ``YYYY_MM.txt`` tables.

    Returns:
        A Markdown table: flag, items, first and last month, example text and whether it is known.
    """
    counts: Counter[str] = Counter()
    first: dict[str, str] = {}
    last: dict[str, str] = {}
    example: dict[str, str] = {}
    for path in sorted(normalized_dir.glob("[12][0-9][0-9][0-9]_[0-9][0-9].txt")):
        with open(path, newline="", encoding="utf-8") as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                if row["kind"] != "I":
                    continue
                flag = row["flag"]
                counts[flag] += 1
                first.setdefault(flag, path.stem)
                last[flag] = path.stem
                example.setdefault(flag, row["text"][:40])
    lines = [
        "| flag | items | first | last | example | known to the normalizer |",
        "|------|------:|-------|------|---------|-------------------------|",
    ]
    for flag, n in counts.most_common():
        shown = f"`{flag}`" if flag else "(none)"
        lines.append(
            f"| {shown} | {n} | {first[flag]} | {last[flag]} | {example[flag]} | "
            f"{'yes' if flag in KNOWN_FLAGS else 'no (rule I13)'} |"
        )
    return "\n".join(lines)


def main(
    write: Annotated[bool, typer.Option(help="Update the generated block in the document.")] = False,
) -> None:
    """Print the flag inventory, or write it into the flag-definitions document."""
    table = inventory(Settings().normalized_dir)
    if not write:
        typer.echo(table)
        return
    text = DOC.read_text(encoding="utf-8")
    block = f"{START}\n{table}\n{END}"
    if START in text:
        head, rest = text.split(START, 1)
        text = head + block + rest.split(END, 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    typer.run(main)
